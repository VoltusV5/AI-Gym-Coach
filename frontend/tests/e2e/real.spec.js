import { test, expect } from '@playwright/test'

test.skip(process.env.SPORTIK_REAL_E2E !== '1', 'Requires isolated Go API with disposable fixture database')
test.describe.configure({ timeout: 65000 })

const fixturePassword = process.env.SPORTIK_E2E_PASSWORD

/** Sign in via the actual v1 flow and wait for the requested destination. */
async function signIn(page, account, destination) {
  const email = process.env[`SPORTIK_E2E_${account.toUpperCase()}_EMAIL`]
  if (!email || !fixturePassword) throw new Error('Provide synthetic fixture account credentials')
  await page.goto('/auth/login?return_to=' + encodeURIComponent(destination))
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Пароль', { exact: true }).fill(fixturePassword)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(destination + '$'))
}

/** Add a real exercise from the deployed catalog to the first training day. */
async function addExercise(page) {
  await page.getByRole('button', { name: 'Добавить упражнение' }).click()
  await page.getByRole('combobox', { name: 'Упражнение', exact: true }).selectOption({ index: 1 })
  await page.getByRole('button', { name: 'Выбрать', exact: true }).click()
}

test('real Go: profile persists, plan saves, workout produces actual progress, free access persists', async ({ page }) => {
  await signIn(page, 'member', '/settings/profile')
  await page.getByLabel('Возраст').fill('27')
  await page.getByLabel('Рост, см').fill('171')
  await page.getByLabel('Вес, кг').fill('72.25')
  await page.getByLabel('Цель').fill('Набрать мышцы')
  await page.getByLabel('Уровень').selectOption('beginner')
  await page.getByLabel('Длительность занятия, мин').fill('45')
  await page.getByLabel('Пн', { exact: true }).check()
  await page.getByRole('button', { name: 'Сохранить профиль' }).click()
  await expect(page.getByText('Профиль сохранён')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Вес, кг')).toHaveValue('72.25')

  await page.goto('/progress')
  const totals = page.getByRole('region', { name: 'Итоги периода' })
  const volume = totals.getByText('Объём', { exact: true }).locator('..').locator('dd')
  await expect(totals).toBeVisible()
  await expect(totals.getByRole('status')).toHaveCount(0)
  const baseline = await volume.count() ? Number((await volume.textContent()).replace(/[^0-9,]/g, '').replace(',', '.')) : 0

  await page.goto('/plans/new')
  const title = 'План браузерной проверки ' + Date.now()
  await page.getByLabel('Название плана').fill(title)
  await page.getByRole('button', { name: 'Создать план' }).click()
  await addExercise(page)
  await page.getByRole('combobox', { name: 'Пн', exact: true }).selectOption({ label: 'День 1' })
  await page.getByRole('button', { name: 'Сохранить план' }).click()
  await expect(page.getByText('План сохранён')).toBeVisible()
  await page.getByRole('link', { name: 'Назад' }).click()
  await expect(page.getByRole('heading', { name: title })).toBeVisible()
  await page.getByRole('button', { name: 'Сделать активным' }).click()
  await expect(page.getByText('Активный план', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Начать тренировку' }).click()
  await page.getByLabel('Подход 1 · повторы').fill('8')
  await page.getByLabel('Подход 1 · вес, кг').fill('12.5')
  await page.getByRole('button', { name: 'Завершить тренировку' }).click()
  await expect(page.getByText('100 кг', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Смотреть прогресс' }).click()
  await expect(page.getByRole('heading', { name: 'Мой прогресс' })).toBeVisible()
  await expect(volume).toHaveText(new Intl.NumberFormat('ru').format(baseline + 100) + ' кг')
  await page.getByRole('link', { name: 'История тренировок' }).click()
  await page.getByRole('link', { name: 'Открыть тренировку' }).first().click()
  await expect(page.getByText(/8 повт. × 12,5 кг/).filter({ visible: true })).toBeVisible()

  await page.goto('/marketplace')
  await page.getByLabel('Цель').fill('Набрать мышцы')
  await page.getByRole('button', { name: 'Применить фильтры' }).click()
  await page.getByRole('link', { name: /Открыть программу/ }).first().click()
  const acquire = page.getByRole('button', { name: 'Получить бесплатно' })
  const entitled = page.getByText('Программа доступна')
  await expect(acquire.or(entitled)).toBeVisible()
  if (await acquire.isVisible()) await acquire.click()
  await expect(page.getByText('Программа доступна')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Программа доступна')).toBeVisible()
})

test('real Go: trainer verification, ownership and program version moderation', async ({ browser }) => {
  const trainer = await browser.newPage()
  const admin = await browser.newPage()
  const other = await browser.newPage()
  try {
    await signIn(trainer, 'trainer', '/trainer/profile')
    await trainer.getByLabel('Имя тренера').fill('Тренер для проверки')
    await trainer.getByLabel('Квалификация', { exact: true }).fill('Публичная квалификация')
    await trainer.getByRole('button', { name: 'Сохранить профиль тренера' }).click()
    await expect(trainer.getByText('Профиль тренера сохранён')).toBeVisible()
    const publicPath = await trainer.getByRole('link', { name: 'Публичный профиль' }).getAttribute('href')
    await trainer.getByRole('link', { name: 'Проверка квалификации' }).click()
    await trainer.getByRole('group', { name: 'Документы и опыт' }).getByRole('textbox', { name: 'Квалификация', exact: true }).fill('Проверяемая квалификация')
    await trainer.getByLabel(/идентификаторы документов/).fill('private/fixture-document')
    await trainer.getByRole('button', { name: 'Отправить на проверку' }).click()
    await expect(trainer.getByText('На проверке', { exact: true })).toBeVisible()

    await signIn(other, 'other', '/admin/verifications')
    await expect(other.getByRole('alert')).toContainText('нет доступа')
    await expect(other.getByText('private/fixture-document')).toHaveCount(0)
    await signIn(admin, 'admin', '/admin/verifications')
    await admin.getByRole('button', { name: 'Рассмотреть' }).first().click()
    await admin.getByLabel('Статус').selectOption('rejected')
    await admin.getByLabel('Причина').fill('Нужна дополнительная справка')
    await admin.getByRole('button', { name: 'Сохранить решение' }).click()
    await expect(admin.getByText('Решение сохранено')).toBeVisible()
    await trainer.getByRole('button', { name: 'Обновить статус' }).click()
    await expect(trainer.getByText(/Нужна дополнительная справка/)).toBeVisible()
    const details = trainer.getByRole('group', { name: 'Документы и опыт' })
    await details.getByRole('textbox', { name: 'Квалификация', exact: true }).fill('Дополненная квалификация')
    await details.getByLabel(/идентификаторы документов/).fill('private/fixture-document')
    await trainer.getByRole('button', { name: 'Отправить на проверку' }).click()
    await expect(trainer.getByText('На проверке', { exact: true })).toBeVisible()
    await admin.reload()
    await admin.getByRole('button', { name: 'Рассмотреть' }).first().click()
    await admin.getByLabel('Статус').selectOption('approved')
    await admin.getByLabel('Причина').fill('Проверка тестового документа')
    await admin.getByRole('button', { name: 'Сохранить решение' }).click()
    await expect(admin.getByText('Решение сохранено')).toBeVisible()
    await trainer.getByRole('button', { name: 'Обновить статус' }).click()
    await expect(trainer.getByText('Подтверждена')).toBeVisible()
    await other.goto(publicPath)
    await expect(other.getByText('Тренер подтверждён')).toBeVisible()
    await expect(other.getByText('private/fixture-document')).toHaveCount(0)

    await trainer.goto('/trainer/programs/new')
    const title = 'Черновик для проверки ' + Date.now()
    await trainer.getByLabel('Название программы').fill(title)
    await trainer.getByLabel('Цель').fill('Общая подготовка')
    await addExercise(trainer)
    const missing = trainer.getByRole('button', { name: 'Добавить необходимое оборудование' })
    if (await missing.isVisible()) await missing.click()
    await trainer.getByRole('button', { name: 'Сохранить черновик' }).click()
    await expect(trainer).toHaveURL(/\/trainer\/programs\/[^/]+\/edit$/)
    const editPath = new URL(trainer.url()).pathname
    const programId = editPath.split('/')[3]
    await other.goto('/marketplace/programs/' + programId)
    await expect(other.getByRole('alert')).toContainText('Эта программа недоступна')
    await other.goto(editPath)
    await expect(other.getByRole('alert')).toContainText('нет доступа')
    await trainer.getByRole('button', { name: 'Отправить на модерацию' }).click()
    await expect(trainer.getByText('На модерации', { exact: true })).toBeVisible()

    await admin.goto('/admin/programs')
    const article = admin.locator('article').filter({ has: admin.getByRole('heading', { name: title, exact: true }) })
    await article.getByRole('button', { name: 'Рассмотреть' }).click()
    await admin.getByLabel('Статус').selectOption('approved')
    await admin.getByLabel('Причина').fill('Состав проверен')
    await admin.getByRole('button', { name: 'Сохранить решение' }).click()
    await expect(admin.getByText('Решение сохранено')).toBeVisible()
    await trainer.getByRole('button', { name: 'Обновить статус' }).click()
    await expect(trainer.getByLabel('Название программы')).toBeDisabled()
    await trainer.getByRole('button', { name: 'Создать новую версию' }).click()
    await expect(trainer.getByLabel('Название программы')).toBeEnabled()
    const nextTitle = title + ' — следующая версия'
    await trainer.getByLabel('Название программы').fill(nextTitle)
    await trainer.getByRole('button', { name: 'Сохранить черновик' }).click()
    await trainer.getByRole('button', { name: 'Отправить на модерацию' }).click()
    await expect(trainer.getByText('На модерации', { exact: true })).toBeVisible()
    await admin.reload()
    const nextArticle = admin.locator('article').filter({ has: admin.getByRole('heading', { name: nextTitle, exact: true }) })
    await nextArticle.getByRole('button', { name: 'Рассмотреть' }).click()
    await admin.getByLabel('Статус').selectOption('rejected')
    await admin.getByLabel('Причина').fill('Версия требует правок')
    await admin.getByRole('button', { name: 'Сохранить решение' }).click()
    await expect(admin.getByText('Решение сохранено')).toBeVisible()
    await trainer.getByRole('button', { name: 'Обновить статус' }).click()
    await expect(trainer.getByText('Отклонена', { exact: true })).toBeVisible()
    await other.goto('/marketplace/programs/' + programId)
    await expect(other.getByRole('heading', { name: title })).toBeVisible()
  } finally {
    await Promise.all([trainer.close(), admin.close(), other.close()])
  }
})

